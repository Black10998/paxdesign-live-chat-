/**
 * Generate navein/inc/cybercrime-countries.php from RestCountries API.
 * Run: node scripts/generate-cybercrime-countries.mjs
 */
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '../navein/inc/cybercrime-countries.php');

function flagEmoji(code) {
  if (!code || code.length !== 2) return '';
  const base = 0x1f1e6;
  return String.fromCodePoint(
    base + code.charCodeAt(0) - 65,
    base + code.charCodeAt(1) - 65
  );
}

function dialCode(idd) {
  if (!idd || !idd.root) return '';
  const root = String(idd.root).replace(/\s/g, '');
  const suffixes = Array.isArray(idd.suffixes) && idd.suffixes.length ? idd.suffixes : [''];
  const suffix = String(suffixes[0] ?? '');
  return root + suffix;
}

function phpEscape(str) {
  return String(str).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const res = await fetch(
  'https://raw.githubusercontent.com/mledoze/countries/master/countries.json'
);
if (!res.ok) {
  console.error('Failed to fetch countries:', res.status);
  process.exit(1);
}
const raw = await res.json();
if (!Array.isArray(raw)) {
  console.error('Unexpected countries payload');
  process.exit(1);
}

const rows = raw
  .filter((c) => c.cca2 && c.name?.common && c.idd?.root)
  .map((c) => {
    const code = c.cca2.toUpperCase();
    const dial = dialCode(c.idd);
    return {
      code,
      dial,
      flag: flagEmoji(code),
      name: {
        en: c.name.common,
        de: c.translations?.deu?.common || c.name.common,
        ar: c.translations?.ara?.common || c.name.common,
      },
    };
  })
  .filter((c) => c.dial)
  .sort((a, b) => a.name.en.localeCompare(b.name.en));

const lines = [
  '<?php',
  '/**',
  ' * Country list for Cybercrime Support portal (ISO 3166-1 alpha-2).',
  ' * Generated by scripts/generate-cybercrime-countries.mjs — do not edit by hand.',
  ' *',
  ' * @package NaveinTheme',
  ' */',
  '',
  "if ( ! defined( 'ABSPATH' ) ) {",
  "\texit;",
  '}',
  '',
  'return array(',
];

for (const row of rows) {
  lines.push(
    `\tarray( 'code' => '${row.code}', 'dial' => '${phpEscape(row.dial)}', 'flag' => '${row.flag}', 'name' => array( 'en' => '${phpEscape(row.name.en)}', 'de' => '${phpEscape(row.name.de)}', 'ar' => '${phpEscape(row.name.ar)}' ) ),`
  );
}

lines.push(');', '');

writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
console.log(`Wrote ${rows.length} countries to ${outPath}`);
